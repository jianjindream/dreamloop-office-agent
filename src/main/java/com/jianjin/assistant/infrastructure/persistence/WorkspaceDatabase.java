package com.jianjin.assistant.infrastructure.persistence;

import com.jianjin.assistant.config.AppConfig;
import com.jianjin.assistant.config.WorkspaceStorageConfig;
import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import jakarta.annotation.PreDestroy;
import org.springframework.stereotype.Component;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/** Dedicated pooled connections: transactions must not share the infrastructure connector's connection. */
@Component
public class WorkspaceDatabase implements AutoCloseable {
    private final HikariDataSource pool;

    public WorkspaceDatabase(WorkspaceStorageConfig storage, AppConfig app) {
        HikariConfig config = new HikariConfig();
        config.setPoolName("workspace");
        config.setMaximumPoolSize(4);
        config.setConnectionTimeout(5000);
        config.setInitializationFailTimeout(5000);
        if ("postgres".equals(storage.getBackend())) {
            config.setJdbcUrl(app.getPgJdbcUrl());
            config.setUsername(app.getPostgres().getUser());
            config.setPassword(app.getPostgres().getPassword());
        } else if ("h2".equals(storage.getBackend())) {
            Path directory = Path.of(storage.getDirectory()).toAbsolutePath().normalize();
            try { Files.createDirectories(directory); }
            catch (Exception e) { throw new IllegalStateException("无法创建工作区存储目录", e); }
            config.setJdbcUrl("jdbc:h2:file:" + directory.resolve("workspace").toString().replace('\\', '/')
                    + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;WRITE_DELAY=0");
            config.setUsername("sa");
            config.setPassword("");
        } else {
            throw new IllegalArgumentException("app.storage.backend 必须为 h2 或 postgres");
        }
        pool = new HikariDataSource(config);
        try {
            transaction(connection -> {
                try (Statement statement = connection.createStatement()) {
                    for (String ddl : SCHEMA) statement.execute(ddl);
                }
                return null;
            });
        } catch (RuntimeException e) { pool.close(); throw e; }
    }

    @FunctionalInterface public interface Work<T> { T run(Connection connection) throws Exception; }

    public <T> T transaction(Work<T> work) {
        try (Connection connection = pool.getConnection()) {
            connection.setAutoCommit(false);
            try {
                T result = work.run(connection);
                connection.commit();
                return result;
            } catch (Exception e) {
                connection.rollback();
                if (e instanceof RuntimeException runtime) throw runtime;
                throw new IllegalStateException("工作区数据读写失败", e);
            }
        } catch (SQLException e) { throw new IllegalStateException("工作区数据库不可用", e); }
    }

    @Override @PreDestroy public void close() { pool.close(); }

    private static final String[] SCHEMA = {
        """
        CREATE TABLE IF NOT EXISTS office_documents (
          id TEXT PRIMARY KEY, title TEXT NOT NULL, doc_type TEXT NOT NULL, source TEXT NOT NULL,
          status TEXT NOT NULL, created_by TEXT NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
          updated_at TIMESTAMP WITH TIME ZONE NOT NULL, latest_version INTEGER NOT NULL, latest_version_id TEXT NOT NULL)
        """,
        """
        CREATE TABLE IF NOT EXISTS office_document_versions (
          id TEXT PRIMARY KEY, document_id TEXT NOT NULL REFERENCES office_documents(id), version INTEGER NOT NULL,
          content_md TEXT NOT NULL, summary TEXT NOT NULL, metadata TEXT NOT NULL,
          created_at TIMESTAMP WITH TIME ZONE NOT NULL, UNIQUE(document_id, version))
        """,
        "CREATE INDEX IF NOT EXISTS idx_office_versions_document ON office_document_versions(document_id, version)",
        """
        CREATE TABLE IF NOT EXISTS chat_sessions (
          user_id TEXT NOT NULL, session_id TEXT NOT NULL, title TEXT NOT NULL DEFAULT '新对话',
          created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
          updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(user_id, session_id))
        """,
        """
        CREATE TABLE IF NOT EXISTS chat_history (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id TEXT NOT NULL DEFAULT 'default',
          session_id TEXT NOT NULL DEFAULT 'default', role TEXT NOT NULL, content TEXT NOT NULL,
          created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP)
        """,
        "CREATE INDEX IF NOT EXISTS idx_chat_history_scope ON chat_history(user_id, session_id, id)"
    };
}
